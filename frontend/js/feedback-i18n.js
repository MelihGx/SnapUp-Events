const RTL = new Set(["ar", "ur", "fa", "he"]);

export function getFeedbackLanguage() {
  const raw = String(
    window.SnapUpI18n?.language ||
      localStorage.getItem("snapup_language") ||
      document.documentElement.lang ||
      "en",
  ).toLowerCase();
  const normalized = ALIASES[raw] || raw;
  return PACKS[normalized] ? normalized : "en";
}

export function getFeedbackDirection(language = getFeedbackLanguage()) {
  return RTL.has(language) ? "rtl" : "ltr";
}

export function feedbackText(key, language = getFeedbackLanguage()) {
  const index = KEYS.indexOf(key);
  if (index < 0) return key;
  return PACKS[language]?.[index] || PACKS.en[index];
}

